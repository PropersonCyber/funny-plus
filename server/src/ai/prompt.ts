/**
 * 提示词的唯一落点，带版本号。
 *
 * 为什么要单独一个文件、还要版本号：
 * 提示词是模型行为的唯一来源，改一句话就会让同一句用户输入产出不同结果。
 * 没有版本号时，「上次那版效果好像更好」永远说不清是哪一版，
 * 也无法把「这轮对话用的是哪一版提示词」和它的产出对上。
 *
 * 版本号随每次 AI 调用上报（见 `ai/observe.ts`），不改提示词就不改号：
 * 改了 `CHAT_SYSTEM_PROMPT` 或 `REVISE_SYSTEM_PROMPT` 的任何一个字，必须同步 +1。
 */

